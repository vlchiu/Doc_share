const assert = require('node:assert/strict');
const { PrismaClient } = require('@prisma/client');
const { PrismaPg } = require('@prisma/adapter-pg');
const { loader } = require('./helpers');
const target = process.env.TEST_DATABASE_URL;
if (!target || !new URL(target).searchParams.get('host')?.startsWith('/tmp/docshare-security-pg.')) throw new Error('Disposable database required');
const db = new PrismaClient({ adapter: new PrismaPg({ connectionString: target }) });
const q = loader({ 'db.js': db }, { ACCOUNT_QUOTAS_ENABLED: 'true', FREE_AI_DAILY_LIMIT: '1', VIP_AI_DAILY_LIMIT: '3', FREE_STORAGE_MB: '1', VIP_STORAGE_MB: '2' })('utils/accountQuota.js');
(async () => {
  const user = await db.user.create({ data: { name: 'Quota fixture', email: 'quota@example.invalid', is_active: true } });
  const outcomes = await Promise.allSettled([q.reserve(user.id, 'AI'), q.reserve(user.id, 'AI')]);
  assert.equal(outcomes.filter(r => r.status === 'fulfilled').length, 1);
  assert.equal(outcomes.find(r => r.status === 'rejected').reason.code, 'AI_QUOTA_EXCEEDED');
  const id = outcomes.find(r => r.status === 'fulfilled').value;
  await q.release(id); // Provider failure refunds slot.
  const paid = await q.reserve(user.id, 'AI');
  await q.complete(paid); await q.release(paid);
  assert.equal(await db.usageReservation.count({ where: { id: paid } }), 1);
  await assert.rejects(q.reserve(user.id, 'AI'), { code: 'AI_QUOTA_EXCEEDED' });
  await db.usageReservation.update({ where: { id: paid }, data: { day: '2000-01-01' } });
  const today = await q.reserve(user.id, 'AI');
  await q.complete(today);
  await db.user.update({ where: { id: user.id }, data: { plan: 'VIP', plan_expires_at: new Date('2099-01-01') } });
  const vip = await q.reserve(user.id, 'AI'); await q.complete(vip);
  await db.user.update({ where: { id: user.id }, data: { plan_expires_at: new Date('2000-01-01') } });
  await assert.rejects(q.reserve(user.id, 'AI'), { code: 'AI_QUOTA_EXCEEDED' });
  const category = await db.category.create({ data: { name: 'Quota fixture' } });
  const doc = await db.document.create({ data: { user_id: user.id, category_id: category.id, title: 'Legacy', file_url: 'fixture', file_type: 'text/plain' } });
  await assert.rejects(q.reserve(user.id, 'STORAGE', 1), { code: 'STORAGE_UNVERIFIED' });
  await db.document.update({ where: { id: doc.id }, data: { file_size: 524288, deleted_at: new Date() } });
  const uploads = await Promise.allSettled([q.reserve(user.id, 'STORAGE', 524288), q.reserve(user.id, 'STORAGE', 524288)]);
  assert.equal(uploads.filter(r => r.status === 'fulfilled').length, 1);
  assert.equal(uploads.find(r => r.status === 'rejected').reason.code, 'STORAGE_QUOTA_EXCEEDED');
  await q.release(uploads.find(r => r.status === 'fulfilled').value);
  await assert.rejects(q.reserve(user.id, 'STORAGE', 524289), { code: 'STORAGE_QUOTA_EXCEEDED' });
  await db.document.delete({ where: { id: doc.id } });
  await q.release(await q.reserve(user.id, 'STORAGE', 1048576));
  assert.equal(q.dayWindow(new Date('2026-11-02T16:59:59Z')).day, '2026-11-02');
  assert.equal(q.dayWindow(new Date('2026-11-02T17:00:00Z')).day, '2026-11-03');
  const chatUser = await db.user.create({ data: { name: 'Quota chat', email: 'quota-chat@example.invalid', is_active: true } });
  const conversation = await db.conversation.create({ data: { user_id: chatUser.id, title: 'Quota chat' } });
  let failAI = true, calls = 0;
  const ai = async (req, res) => { calls++; return failAI ? res.status(500).json({}) : res.json({ reply: 'Test reply' }); };
  const controller = loader({ 'db.js': db, 'controllers/chatController.js': { chatGeneral: ai, chatWithDocument: ai } }, { ACCOUNT_QUOTAS_ENABLED: 'true', FREE_AI_DAILY_LIMIT: '1' })('controllers/conversationController.js');
  const { response } = require('./helpers');
  const req = { user: { userId: chatUser.id, role: 'USER' }, params: { id: conversation.id }, body: { message: 'Question', requestId: require('node:crypto').randomUUID() } };
  let res = response(); await controller.send(req, res); assert.equal(res.statusCode, 502);
  assert.equal(await db.usageReservation.count({ where: { user_id: chatUser.id } }), 0);
  failAI = false;
  res = response(); await controller.send(req, res); assert.equal(res.statusCode, 200);
  res = response(); await controller.send(req, res); assert.equal(res.statusCode, 200);
  assert.equal(calls, 2);
  req.body.requestId = require('node:crypto').randomUUID();
  res = response(); await controller.send(req, res); assert.equal(res.statusCode, 429);
  assert.equal(await db.chatMessage.count({ where: { conversation_id: conversation.id } }), 2);
  console.log('PASS quotas PostgreSQL: concurrent AI/storage, refund, completed charge, day reset, VIP expiry, unknown legacy bytes, trash and permanent deletion.');
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(() => db.$disconnect());
